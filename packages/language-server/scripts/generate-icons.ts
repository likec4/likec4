import { fdir } from 'fdir'
import { mkdirSync, writeFileSync } from 'node:fs'
import { sep } from 'path'

const crawled = new fdir()
  .filter((name, isDir) => !isDir && (name.endsWith('.tsx') || name.endsWith('.js')))
  .withFullPaths()
  .crawl('../icons')
  .sync()

const tsxPaths = new Set(crawled.filter(file => file.endsWith('.tsx')))
// md/*.tsx is generated and gitignored. A cache hit restores md/*.js.
const files = crawled.filter(file => {
  if (file.endsWith('.tsx')) {
    return true
  }
  const base = file.slice(file.lastIndexOf(sep) + 1)
  if (base === 'index.js' || base === 'all.js') {
    return false
  }
  return !tsxPaths.has(`${file.slice(0, -'.js'.length)}.tsx`)
}).sort()

console.info(`Found ${files.length} files`)

let added = 0
const grouped = files.reduce((acc, path) => {
  const parts = path.split(sep)
  const icon = (parts.pop() || 'invalid').replace(/\.tsx$/, '').replace(/\.js$/, '')
  const group = parts.pop() || 'error'
  if (!['aws', 'azure', 'gcp', 'md', 'tech', 'bootstrap'].includes(group)) {
    console.error(`Unknown group ${group}`)
    return acc
  }
  added++
  acc[group as keyof typeof acc].push(icon)
  return acc
}, {
  aws: [] as string[],
  azure: [] as string[],
  gcp: [] as string[],
  md: [] as string[],
  tech: [] as string[],
  bootstrap: [] as string[],
})

if (grouped.md.length === 0) {
  throw new Error('Material Symbols are missing. Run generate in @likec4/icons before building the icon registry.')
}

const source = `// @ts-nocheck
// THIS FILE IS AUTO-GENERATED. DO NOT EDIT THIS FILE DIRECTLY.
// Generated from @likec4/icons
const groupedIcons = {
  aws: ${JSON.stringify(grouped.aws)},
  azure: ${JSON.stringify(grouped.azure)},
  gcp: ${JSON.stringify(grouped.gcp)},
  md: ${JSON.stringify(grouped.md)},
  tech: ${JSON.stringify(grouped.tech)},
  bootstrap: ${JSON.stringify(grouped.bootstrap)},
} as const

export type IconGroup = keyof typeof groupedIcons

export const iconGroups: IconGroup[] = Object.keys(groupedIcons) as IconGroup[]

export type GroupedIcons = Record<IconGroup, readonly string[]>

/**
 * Grouped icon registry: maps each icon group name to its list of icon names.
 */
export const iconRegistry: GroupedIcons = groupedIcons

const icons = [...Object.entries(groupedIcons)]
  .flatMap(([group, names]) => names.map((name) => group + ':' + name))

export const LibIcons: string = [
  'likec4lib {',
  '  icons {',
  ...icons.map((icon) => '    ' + icon),
  '  }',
  '}',
].join('\\n')
`

mkdirSync('src/generated', { recursive: true })
writeFileSync('src/generated/icons.ts', source, 'utf-8')

console.info(`Generated src/generated/icons.ts with`, added, `icons`)
