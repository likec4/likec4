import type { ThemeColor } from '../../styles/types'
import type {
  _stage,
  _type,
  BaseViewProperties,
  BBox,
  ComputedEdge,
  ComputedNode,
  DiagramEdge,
  DiagramNode,
  EdgeRouting,
  NodeId,
  ProjectId,
  ViewAutoLayout,
} from '../../types'

/**
 * Size of a project's model, shown on the projects overview
 */
export interface ProjectMetrics {
  readonly elements: number
  readonly relationships: number
  readonly views: number
}

export interface ProjectsOverviewGroupBy {
  readonly key: string
  /** Colors the frames of this level by value. Unmapped values stay gray. */
  readonly colors?: Readonly<Record<string, ThemeColor>> | undefined
  readonly thenBy?: ProjectsOverviewGroupBy | undefined
}

export interface ProjectsOverviewColorBy {
  readonly key: string
  readonly colors: Readonly<Record<string, ThemeColor>>
}

export interface ProjectsOverviewExclude {
  readonly key: string
  readonly values: readonly string[]
}

export interface ProjectsOverviewOptions {
  /** Hides the projects whose metadata `key` has one of the `values`. Edges to hidden projects are dropped. */
  readonly exclude?: ProjectsOverviewExclude | undefined
  readonly groupBy?: ProjectsOverviewGroupBy | undefined
  /** Stacks the groups of the first `groupBy` key top to bottom. Unlisted values follow, alphabetically. */
  readonly order?: readonly string[] | undefined
  readonly colorBy?: ProjectsOverviewColorBy | undefined
  readonly routing?: EdgeRouting | undefined
}

/** One value of `colorBy` among the shown projects. */
export interface ProjectsOverviewLegendEntry {
  readonly value: string
  readonly color: ThemeColor
  /** Number of shown projects with this value */
  readonly count: number
}

/** Explains the colors of the overview. Set when the overview has `colorBy`. */
export interface ProjectsOverviewLegend {
  readonly colorBy: {
    readonly key: string
    readonly entries: ReadonlyArray<ProjectsOverviewLegendEntry>
  }
}

export interface ComputedProjectNode extends ComputedNode {
  readonly kind: '@project'
  readonly projectId: ProjectId
  /**
   * Optional, as layouted views generated by older versions don't have it
   */
  readonly metrics?: ProjectMetrics
}

export interface ComputedProjectGroupNode extends ComputedNode {
  readonly kind: '@group'
}

export interface ComputedProjectEdge extends ComputedEdge {
  readonly projectId: ProjectId
}

export type ComputedProjectsNode = ComputedProjectNode | ComputedProjectGroupNode

export interface LayoutedProjectNode extends DiagramNode {
  readonly kind: '@project'
  readonly projectId: ProjectId
  /**
   * Optional, as layouted views generated by older versions don't have it
   */
  readonly metrics?: ProjectMetrics
}

export interface LayoutedProjectGroupNode extends DiagramNode {
  readonly kind: '@group'
}

export type LayoutedProjectsNode = LayoutedProjectNode | LayoutedProjectGroupNode

export interface LayoutedProjectEdge extends DiagramEdge {
  readonly projectId: ProjectId
}

/**
 * An overview of projects and their relationships, presented as a graph with nodes and edges.
 * Even though it has same structure as other likec4 views, it is not mixed with them, as it represents a different kind.
 */
export interface ComputedProjectsView extends BaseViewProperties<any> {
  readonly [_type]: 'projects'
  readonly [_stage]: 'computed'
  readonly nodes: ReadonlyArray<ComputedProjectsNode>
  readonly edges: ReadonlyArray<ComputedProjectEdge>
  readonly autoLayout: ViewAutoLayout
  /** Top-level groups, stacked top to bottom as bands. Set when the overview has an `order`. */
  readonly layers?: ReadonlyArray<NodeId> | undefined
  readonly legend?: ProjectsOverviewLegend | undefined
}

export interface LayoutedProjectsView extends BaseViewProperties<any> {
  readonly [_type]: 'projects'
  readonly [_stage]: 'layouted'
  readonly nodes: ReadonlyArray<LayoutedProjectsNode>
  readonly edges: ReadonlyArray<LayoutedProjectEdge>
  readonly bounds: BBox
  readonly legend?: ProjectsOverviewLegend | undefined
}
