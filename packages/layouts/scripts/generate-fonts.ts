/**
 * Embeds IBM Plex Sans (font of the diagram) for measuring labels.
 *
 * Fonts are taken from @fontsource-variable/ibm-plex-sans (same unicode-range subsets the diagram loads),
 * decompressed from WOFF2 and stripped down to metrics:
 * - glyph outlines are removed (`glyf` and `loca` are emptied, `gvar` has no deltas)
 * - hinting and naming tables are dropped
 * Advances (hmtx, HVAR), kerning (GPOS) and ligatures (GSUB) are kept intact.
 */
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { decompress } from 'wawoff2'

export const Subsets = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'greek'] as const

const DropTables = new Set(['fpgm', 'prep', 'cvt ', 'cvar', 'gasp', 'name', 'STAT', 'post', 'DSIG'])

type Table = { tag: string; data: Uint8Array }

function readTables(ttf: Uint8Array): { sfntVersion: number; tables: Table[] } {
  const view = new DataView(ttf.buffer, ttf.byteOffset, ttf.byteLength)
  const count = view.getUint16(4)
  const tables: Table[] = []
  for (let i = 0; i < count; i++) {
    const record = 12 + i * 16
    const tag = String.fromCharCode(...ttf.subarray(record, record + 4))
    const offset = view.getUint32(record + 8)
    const length = view.getUint32(record + 12)
    tables.push({ tag, data: ttf.subarray(offset, offset + length) })
  }
  return { sfntVersion: view.getUint32(0), tables }
}

/**
 * gvar without any glyph variations (header + zero offsets).
 * fontkit requires gvar for variable fonts, advances are taken from HVAR
 */
function emptyGvar(gvar: Uint8Array): Uint8Array {
  const view = new DataView(gvar.buffer, gvar.byteOffset, gvar.byteLength)
  const axisCount = view.getUint16(4)
  const glyphCount = view.getUint16(12)
  const dataOffset = 20 + (glyphCount + 1) * 2
  const out = new Uint8Array(dataOffset)
  const outView = new DataView(out.buffer)
  outView.setUint32(0, 0x00010000) // version
  outView.setUint16(4, axisCount)
  outView.setUint16(6, 0) // sharedTupleCount
  outView.setUint32(8, dataOffset) // sharedTuplesOffset
  outView.setUint16(12, glyphCount)
  outView.setUint16(14, 0) // flags: short offsets
  outView.setUint32(16, dataOffset) // glyphVariationDataArrayOffset
  return out
}

function stripFont(ttf: Uint8Array): Uint8Array {
  const { sfntVersion, tables } = readTables(ttf)
  const kept = tables
    .filter(t => !DropTables.has(t.tag))
    .map((t): Table => {
      switch (t.tag) {
        case 'glyf':
          return { tag: t.tag, data: new Uint8Array(0) }
        case 'loca':
          // all glyphs are empty
          return { tag: t.tag, data: new Uint8Array(t.data.length) }
        case 'gvar':
          return { tag: t.tag, data: emptyGvar(t.data) }
        default:
          return t
      }
    })
    .sort((a, b) => (a.tag < b.tag ? -1 : 1))

  const count = kept.length
  const entrySelector = Math.floor(Math.log2(count))
  const searchRange = 2 ** entrySelector * 16
  let size = 12 + count * 16
  for (const t of kept) size += (t.data.length + 3) & ~3

  const out = new Uint8Array(size)
  const view = new DataView(out.buffer)
  view.setUint32(0, sfntVersion)
  view.setUint16(4, count)
  view.setUint16(6, searchRange)
  view.setUint16(8, entrySelector)
  view.setUint16(10, count * 16 - searchRange)
  let offset = 12 + count * 16
  kept.forEach((t, i) => {
    const record = 12 + i * 16
    for (let k = 0; k < 4; k++) out[record + k] = t.tag.charCodeAt(k)
    // checksums are not validated by fontkit
    view.setUint32(record + 8, offset)
    view.setUint32(record + 12, t.data.length)
    out.set(t.data, offset)
    offset += (t.data.length + 3) & ~3
  })
  return out
}

export async function generateFonts(): Promise<string> {
  const require = createRequire(import.meta.url)
  const fontDir = dirname(require.resolve('@fontsource-variable/ibm-plex-sans/index.css'))
  const fonts: string[] = []
  for (const subset of Subsets) {
    const woff2 = readFileSync(resolve(fontDir, `files/ibm-plex-sans-${subset}-wght-normal.woff2`))
    // copy, decompressed data is a view into shared wasm memory
    const ttf = (await decompress(woff2)).slice()
    fonts.push(Buffer.from(stripFont(ttf)).toString('base64'))
  }
  return [
    `// Generated by scripts/generate-fonts.ts, do not edit`,
    `//`,
    `// Metrics-only subset of IBM Plex Sans Variable (glyph outlines removed),`,
    `// Copyright 2019 IBM Corp. All rights reserved.`,
    `// Licensed under the SIL Open Font License, Version 1.1, see OFL.txt`,
    ``,
    `/**`,
    ` * Base64-encoded TTF faces (unicode-range subsets: ${Subsets.join(', ')})`,
    ` */`,
    `export const IBMPlexSansFaces: string[] = ${JSON.stringify(fonts, null, 2)}`,
    ``,
  ].join('\n')
}
