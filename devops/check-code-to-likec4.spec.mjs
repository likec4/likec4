import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { afterEach, describe, it } from 'node:test'

const repoRoot = path.resolve(import.meta.dirname, '..')
const skillDir = path.join(repoRoot, 'skills/code-to-likec4')
const tempRoots = []

const run = (script, args) =>
  execFileSync(process.execPath, [path.join(skillDir, 'scripts', script), ...args], {
    cwd: repoRoot,
    encoding: 'utf8',
    stdio: 'pipe',
  })

afterEach(() => {
  while (tempRoots.length > 0) {
    rmSync(tempRoots.pop(), { recursive: true, force: true })
  }
})

void describe('code-to-likec4 skill', () => {
  void it('scans, labels, and emits a validated model', () => {
    const root = mkdtempSync(path.join(tmpdir(), 'code-to-likec4-'))
    tempRoots.push(root)
    mkdirSync(path.join(root, 'src'), { recursive: true })
    writeFileSync(
      path.join(root, 'src/store.ts'),
      `export class Store {\n  get(key: string) { return key }\n}\n`,
    )
    writeFileSync(
      path.join(root, 'src/app.ts'),
      `import { Store } from './store'\n\nexport class App {\n  constructor(private store: Store) {}\n}\n`,
    )

    const ir = path.join(root, 'ir.json')
    const labeled = path.join(root, 'ir.labeled.json')
    const out = path.join(root, 'generated')

    run('scan.mjs', ['--root', root, '--out', ir])
    run('auto-label.mjs', ['--in', ir, '--out', labeled, '--system', 'demo'])
    run('emit.mjs', ['--in', labeled, '--out', out, '--system', 'demo'])

    const spec = readFileSync(path.join(out, 'spec.c4'), 'utf8')
    const model = readFileSync(path.join(out, 'model.c4'), 'utf8')
    const views = readFileSync(path.join(out, 'views.c4'), 'utf8')

    for (const source of [spec, model, views]) {
      assert.match(source, /^\/\/ Generated by code-to-likec4/)
      assert.doesNotMatch(source, /#autogenerated/)
    }
    assert.match(model, /= system 'demo'/)
    assert.match(model, /component 'app'/)
    assert.match(model, /demo\.src\.app -> demo\.src\.store/)
    assert.match(views, /view of_demo of demo/)
  })
})
