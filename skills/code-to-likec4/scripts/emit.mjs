#!/usr/bin/env node
// emit.mjs — IR JSON -> spec.c4 / model.c4 / views.c4 via string template (zero deps).
// Usage: node emit.mjs --in <ir.json> --out <dir> [--system <name>]
// IR: { elements: [{fqn?, kind?, title, file, lang, symbol?, line?, parent?, route?, imports?, calls?, extends?, technology?, tags?}], proposals? }
// - relationship entries may be strings (default kind) or {to, kind?, label?, line?} objects.
// - scanner `calls` entries that match a sibling symbol name resolve to inproc edges.
// - provenance: file header comments (no per-element tags — tags render as badges).
// Importable for unit tests: `import { sanitize, emitModel } from './emit.mjs'`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export function help() {
  console.log(`emit.mjs — emit LikeC4 sources from labeled IR
Usage: node emit.mjs --in <ir.json> --out <dir> [--system <name>] [--check] [--drop-symbols]
Fails closed on duplicate FQN, bad identifier, or unknown relationship kind.
--drop-symbols keeps file-level elements + route handlers only (drops helper
class/function/variable symbols) — use when the model has too many elements.
--check runs LikeC4.fromSource().getErrors() when the likec4 package is
installed (skipped with a note otherwise); template output stays canonical.`)
}

const IDENT_RE = /^[A-Za-z_][A-Za-z0-9_-]*$/
export const REL_KINDS = new Set(['http', 'kafka', 's3', 'promql', 'inproc', 'calls', 'imports', 'inherits'])
// LikeC4 DSL reserved words (verified: `order`; rest are language keywords that
// break parsing in identifier position). Matched case-insensitively.
const RESERVED = new Set([
  'specification',
  'element',
  'deploymentnode',
  'relationship',
  'tag',
  'color',
  'model',
  'views',
  'view',
  'deployment',
  'global',
  'include',
  'exclude',
  'extend',
  'extends',
  'style',
  'title',
  'description',
  'summary',
  'notation',
  'technology',
  'link',
  'shape',
  'icon',
  'border',
  'opacity',
  'multiple',
  'navigateto',
  'autolayout',
  'order',
  'group',
  'node',
  'instance',
  'filter',
  'with',
  'of',
  'dynamic',
  'where',
])
export const sanitize = (s) => {
  let out = String(s).replace(/[^A-Za-z0-9_-]/g, '_').replace(/^([0-9])/, '_$1') || 'unnamed'
  if (RESERVED.has(out.toLowerCase())) out = `${out}_`
  return out
}
export const isIdent = (s) => IDENT_RE.test(s)

export function parseArgs(argv) {
  const o = { in: '', out: '', system: 'cloud', check: false, dropSymbols: false }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--in') o.in = argv[++i]
    else if (a === '--out') o.out = argv[++i]
    else if (a === '--system') o.system = argv[++i]
    else if (a === '--check') o.check = true
    else if (a === '--drop-symbols') o.dropSymbols = true
    else if (a === '-h' || a === '--help') {
      help()
      process.exit(0)
    }
  }
  if (!o.in || !o.out) {
    help()
    process.exit(2)
  }
  return o
}

export function areaOf(file) {
  const parts = String(file || '').split('/')
  return parts.length > 1 ? sanitize(parts[0]) : 'app'
}

export function normRel(r, defaultKind) {
  if (typeof r === 'string') return { to: r, kind: defaultKind, label: '', line: 0 }
  return { to: r.to, kind: r.kind || defaultKind, label: r.label || '', line: r.line || 0 }
}

export const HEADER = '// Generated by code-to-likec4 — do not hand-edit. Regenerate via emit.mjs.'

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, '\\\'').replace(/\r?\n/g, ' ')}'`

